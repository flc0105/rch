
class AgentBootstrapScriptService:
    """
    Agent bootstrap 脚本生成服务。

    职责：
    - 校验并归一化 bootstrap 请求参数
    - 生成跨平台 Python bootstrap 脚本
    - 生成 Windows PowerShell bootstrap 脚本
    """

    def normalize_bootstrap_payload(self, payload: dict) -> dict:
        if not isinstance(payload, dict):
            raise ValueError('Invalid bootstrap payload')

        server_host = (payload.get('server_host') or '').strip()
        server_port = payload.get('server_port')
        web_port = payload.get('web_port')
        web_host = (payload.get('web_host') or server_host).strip() or server_host
        web_scheme = (payload.get('web_scheme') or 'http').strip() or 'http'

        if not server_host:
            raise ValueError('server_host is required')
        if not server_port:
            raise ValueError('server_port is required')
        if not web_port:
            raise ValueError('web_port is required')

        try:
            server_port = int(server_port)
        except (ValueError, TypeError):
            raise ValueError('server_port must be integer')

        try:
            web_port = int(web_port)
        except (ValueError, TypeError):
            raise ValueError('web_port must be integer')

        if not 1 <= web_port <= 65534:
            raise ValueError('web_port must be between 1 and 65534')

        return {
            'server_host': server_host,
            'server_port': server_port,
            'web_host': web_host,
            'web_port': web_port,
            'web_scheme': web_scheme,
        }

    def generate_python_script(self, payload: dict) -> str:
        params = self.normalize_bootstrap_payload(payload)
        return self._generate_python_script(
            params['server_host'],
            params['server_port'],
            params['web_host'],
            params['web_port'],
            params['web_scheme'],
        )

    def generate_powershell_script(self, payload: dict) -> str:
        params = self.normalize_bootstrap_payload(payload)
        return self._generate_powershell_script(
            params['server_host'],
            params['server_port'],
            params['web_port'],
        )

    def _generate_python_script(self, server_host, server_port, web_host, web_port, web_scheme='http'):
        import json
        script = _PYTHON_BOOTSTRAP
        for key, value in {
            '@SERVER_HOST@': json.dumps(server_host),
            '@SERVER_PORT@': str(server_port),
            '@WEB_HOST@': json.dumps(web_host),
            '@WEB_PORT@': str(web_port),
            '@WEB_SCHEME@': json.dumps(web_scheme),
        }.items():
            script = script.replace(key, value)
        return script

    def _generate_powershell_script(self, server_host, server_port, web_port):
        import json
        script = _POWERSHELL_BOOTSTRAP
        for key, value in {
            '@SERVER_HOST@': json.dumps(server_host),
            '@SERVER_PORT@': str(server_port),
            '@WEB_PORT@': str(web_port),
        }.items():
            script = script.replace(key, value)
        return script


# Both bootstrap entrypoints follow the same release layout and SHA-256 contract.
# Their platform-specific interpreter selection is deliberate (Windows Embed, macOS local).
_PYTHON_BOOTSTRAP = r'''# bootstrap.py - Cross-platform bootstrap script
# Generated by server API
import hashlib
import json
import os
import runpy
import re
import shutil
import subprocess
import sys
import threading
import time
import urllib.request
import zipfile
from pathlib import Path
from urllib.parse import urljoin

SERVER_HOST = @SERVER_HOST@
SERVER_PORT = @SERVER_PORT@
WEB_HOST = @WEB_HOST@
WEB_PORT = @WEB_PORT@
WEB_SCHEME = @WEB_SCHEME@
BASE_URL = f"{WEB_SCHEME}://{WEB_HOST}:{WEB_PORT}"
ROOT = Path.home() / 'client_bundle'
RUNTIME_DIR = ROOT / 'runtimes' / 'python-embed'
DOWNLOADS_DIR = ROOT / 'downloads'
RELEASES_DIR = ROOT / 'releases'
MIN_PYTHON = (3, 10)


def log(message):
    print(f'[bootstrap] {message}', flush=True)


def request_bytes(url, payload=None):
    body = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(url, data=body, headers={'Content-Type': 'application/json'} if body else {})
    with urllib.request.urlopen(request, timeout=300) as response:
        return response.read()


def runtime_version(python):
    try:
        result = subprocess.run([str(python), '-c', 'import sys; print(sys.version_info.major,sys.version_info.minor)'],
                                capture_output=True, text=True, timeout=12, check=True)
        major, minor = map(int, result.stdout.strip().split())
        return major, minor
    except (OSError, ValueError, subprocess.SubprocessError):
        return (0, 0)


def find_embedded(root):
    return next((p for p in sorted(root.rglob('python.exe')) if p.is_file()), None) if root.is_dir() else None


def download(url, dest, sha256=None):
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_name(dest.name + '.part')
    digest = hashlib.sha256()
    try:
        with urllib.request.urlopen(url, timeout=300) as response, open(tmp, 'wb') as output:
            while True:
                chunk = response.read(1024 * 1024)
                if not chunk:
                    break
                output.write(chunk)
                digest.update(chunk)
        if sha256 and digest.hexdigest().lower() != sha256.lower():
            raise ValueError('Downloaded file SHA-256 mismatch')
        os.replace(tmp, dest)
    finally:
        if tmp.exists():
            tmp.unlink()


def extract_zip(zip_path, destination):
    # Validate members before extraction and never extract symlinks.
    destination.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path) as archive:
        if archive.testzip() is not None:
            raise ValueError('ZIP CRC verification failed')
        for member in archive.infolist():
            name = member.filename.replace('\\', '/')
            path = Path(name)
            if path.is_absolute() or '..' in path.parts or (member.external_attr >> 16) & 0o170000 == 0o120000:
                raise ValueError(f'Unsafe ZIP member: {name}')
        archive.extractall(destination)


def prepare_python():
    if sys.platform != 'win32':
        for candidate in (sys.executable, shutil.which('python3'), shutil.which('python')):
            if candidate and runtime_version(candidate) >= MIN_PYTHON:
                return str(candidate)
        raise RuntimeError('Python 3.10 or newer is required')

    embedded = find_embedded(RUNTIME_DIR)
    if embedded and runtime_version(embedded) >= MIN_PYTHON:
        return str(embedded)
    for candidate in (sys.executable, shutil.which('python'), shutil.which('python3')):
        if candidate and runtime_version(candidate) >= MIN_PYTHON:
            return str(candidate)

    # Python 3.13 Embed is packaged only for supported Windows amd64.
    import platform
    system_version = sys.getwindowsversion()
    if (system_version.major, system_version.minor) < (6, 3):
        raise RuntimeError('Python 3.13 Embed requires Windows 8.1 or newer')
    arch = platform.machine().lower()
    if arch in ('amd64', 'x86_64'):
        arch = 'amd64'
    if arch != 'amd64':
        raise RuntimeError(f'No embedded Python package available for Windows {arch}')
    url = f'{BASE_URL}/api/external-tools/python-embed/download?platform=win&arch={arch}'
    zip_path = DOWNLOADS_DIR / 'python-embed.zip'
    download(url, zip_path)
    staging = RUNTIME_DIR.with_name('python-embed.part')
    if staging.exists():
        shutil.rmtree(staging)
    try:
        extract_zip(zip_path, staging)
        found = find_embedded(staging)
        if not found or runtime_version(found) < MIN_PYTHON:
            raise RuntimeError('Downloaded Python runtime is missing or incompatible')
        relative = found.relative_to(staging)
        if RUNTIME_DIR.exists():
            shutil.rmtree(RUNTIME_DIR)
        staging.rename(RUNTIME_DIR)
        return str(RUNTIME_DIR / relative)
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def build_bundle():
    payload = {
        'server_host': SERVER_HOST, 'server_port': SERVER_PORT,
        'server_web_scheme': WEB_SCHEME, 'server_web_host': WEB_HOST,
        'web_port': WEB_PORT, 'target_os': 'bundle', 'builder': 'bundle',
        'target_arch': '', 'source': 'bootstrap',
    }
    result = json.loads(request_bytes(f'{BASE_URL}/api/agent/build', payload))
    if result.get('code') != 0:
        raise RuntimeError(result.get('message') or 'Bundle build failed')
    return result['data']


def launch(python, directory):
    script = directory / 'rchclient.py'
    if not script.is_file():
        raise FileNotFoundError(script)
    try:
        import appex
        pythonista = True
    except ImportError:
        pythonista = sys.platform == 'ios'
    if pythonista:
        def run():
            os.chdir(directory)
            sys.path.insert(0, str(directory))
            sys.argv = [str(script)]
            runpy.run_path(str(script), run_name='__main__')
        threading.Thread(target=run, name='rchclient-main', daemon=False).start()
        return
    kwargs = {'cwd': str(directory), 'stdin': subprocess.DEVNULL,
              'stdout': subprocess.DEVNULL, 'stderr': subprocess.DEVNULL, 'close_fds': True}
    if sys.platform == 'win32':
        kwargs['creationflags'] = 0x00000008 | 0x00000200
    else:
        kwargs['start_new_session'] = True
    subprocess.Popen([str(python), str(script)], **kwargs)


def main():
    DOWNLOADS_DIR.mkdir(parents=True, exist_ok=True)
    RELEASES_DIR.mkdir(parents=True, exist_ok=True)
    python = prepare_python()
    meta = build_bundle()
    version = meta['build_version']
    filename = meta['file_name']
    if not all(re.fullmatch(r'[A-Za-z0-9._-]+', value) and value not in ('.', '..')
               for value in (version, filename)):
        raise ValueError('Invalid build metadata path')
    expected_sha = meta.get('sha256')
    if not expected_sha:
        raise ValueError('Bundle build did not provide SHA-256')
    archive_path = DOWNLOADS_DIR / filename
    download(urljoin(BASE_URL + '/', meta['download_url']), archive_path, expected_sha)
    release = RELEASES_DIR / version
    staging = RELEASES_DIR / (version + '.part')
    if staging.exists():
        shutil.rmtree(staging)
    try:
        extract_zip(archive_path, staging)
        if not (staging / 'rchclient.py').is_file():
            raise RuntimeError('Bundle missing rchclient.py')
        if release.exists():
            shutil.rmtree(release)
        staging.rename(release)
    finally:
        if staging.exists():
            shutil.rmtree(staging)
    launch(python, release)
    log('handoff done, bootstrap exits')


if __name__ == '__main__':
    main()
'''

_POWERSHELL_BOOTSTRAP = r'''$ErrorActionPreference = 'Stop'
$ip = @SERVER_HOST@
$serverPort=@SERVER_PORT@
$webPort=@WEB_PORT@
$bundleDir = Join-Path $env:USERPROFILE 'client_bundle'
$runtimeDir = Join-Path $bundleDir 'runtimes\python-embed'
$downloadsDir = Join-Path $bundleDir 'downloads'
$releaseDir = Join-Path $bundleDir 'releases'
New-Item -Type Directory -Force $downloadsDir,$releaseDir | Out-Null

function Test-Python($binary) {
    try {
        $text = & $binary -c 'import sys; print(sys.version_info.major, sys.version_info.minor)' 2>$null
        if ($LASTEXITCODE -ne 0) { return $false }
        $parts = ("$text".Trim() -split '\s+')
        return ([int]$parts[0] -gt 3 -or ([int]$parts[0] -eq 3 -and [int]$parts[1] -ge 10))
    } catch { return $false }
}

function Find-Embed($folder) {
    if (-not (Test-Path $folder)) { return $null }
    return Get-ChildItem $folder -Filter python.exe -Recurse -File -ErrorAction SilentlyContinue |
        Select-Object -First 1 -ExpandProperty FullName
}

function Get-Hash256($path) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $stream = [System.IO.File]::OpenRead($path)
    try { return ([BitConverter]::ToString($sha.ComputeHash($stream))).Replace('-', '').ToLowerInvariant() }
    finally { $stream.Dispose(); $sha.Dispose() }
}

function Expand-ValidatedZip($archivePath, $destination) {
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $zip = [System.IO.Compression.ZipFile]::OpenRead($archivePath)
    try {
        $root = [IO.Path]::GetFullPath($destination).TrimEnd('\') + '\'
        foreach ($entry in $zip.Entries) {
            $target = [IO.Path]::GetFullPath((Join-Path $root $entry.FullName))
            if (-not $target.StartsWith($root, [StringComparison]::OrdinalIgnoreCase)) {
                throw "Unsafe ZIP member: $($entry.FullName)"
            }
        }
    } finally { $zip.Dispose() }
    New-Item -ItemType Directory -Force $destination | Out-Null
    [System.IO.Compression.ZipFile]::ExtractToDirectory($archivePath, $destination)
}

# Windows: embedded runtime first, then suitable local Python, then download Embed.
$py = Find-Embed $runtimeDir
if ($py -and -not (Test-Python $py)) { $py = $null }
if (-not $py) {
    foreach ($candidate in @('python','python3')) {
        if (Test-Python $candidate) { $py = $candidate; break }
    }
}
if (-not $py) {
    if (Get-Command Get-CimInstance -ErrorAction SilentlyContinue) {
        $osInfo = Get-CimInstance Win32_OperatingSystem
    } else {
        $osInfo = Get-WmiObject Win32_OperatingSystem
    }
    $windowsVersion = [Version]$osInfo.Version
    if ($windowsVersion -lt [Version]'6.3') { throw 'Python 3.13 Embed requires Windows 8.1 or newer' }
    $arch = $env:PROCESSOR_ARCHITEW6432
    if (-not $arch) { $arch = $env:PROCESSOR_ARCHITECTURE }
    if ($arch -eq 'AMD64') { $arch = 'amd64' }
    if ($arch -ne 'amd64') { throw "No embedded Python package available for Windows $arch" }
    $zipPath = Join-Path $downloadsDir 'python-embed.zip'
    Invoke-WebRequest "http://$ip`:$webPort/api/external-tools/python-embed/download?platform=win&arch=$arch" -OutFile $zipPath -UseBasicParsing
    $staging = "$runtimeDir.part"
    if (Test-Path $staging) { Remove-Item $staging -Recurse -Force }
    Expand-ValidatedZip $zipPath $staging
    $candidate = Find-Embed $staging
    if (-not $candidate -or -not (Test-Python $candidate)) { throw 'Downloaded Embed is incompatible' }
    $relative = $candidate.Substring($staging.Length).TrimStart('\')
    if (Test-Path $runtimeDir) { Remove-Item $runtimeDir -Recurse -Force }
    Move-Item $staging $runtimeDir
    $py = Join-Path $runtimeDir $relative
}

$body = @{
    server_host=$ip; server_port=$serverPort; web_port=$webPort;
    target_os='bundle'; builder='bundle'; target_arch=''; source='bootstrap';
    server_web_scheme='http'; server_web_host=$ip
} | ConvertTo-Json -Compress
$response = Invoke-RestMethod "http://$ip`:$webPort/api/agent/build" -Method Post -ContentType 'application/json' -Body $body
if ($response.code -ne 0) { throw "Build failed: $($response.message)" }
$data = $response.data
if (-not $data.sha256) { throw 'Build response missing SHA-256' }
if ($data.file_name -notmatch '^[A-Za-z0-9._-]+$' -or
    $data.build_version -notmatch '^[A-Za-z0-9._-]+$' -or
    $data.file_name -in @('.', '..') -or $data.build_version -in @('.', '..')) {
    throw 'Invalid build metadata path'
}
$url = $data.download_url
if (-not $url.StartsWith('http')) { $url = "http://$ip`:$webPort$url" }
$zipPath = Join-Path $downloadsDir $data.file_name
Invoke-WebRequest $url -OutFile $zipPath -UseBasicParsing
if ((Get-Hash256 $zipPath) -ne $data.sha256.ToLowerInvariant()) { throw 'Bundle SHA-256 mismatch' }
$release = Join-Path $releaseDir $data.build_version
$staging = "$release.part"
if (Test-Path $staging) { Remove-Item $staging -Recurse -Force }
try {
    Expand-ValidatedZip $zipPath $staging
    if (-not (Test-Path (Join-Path $staging 'rchclient.py'))) { throw 'Bundle missing rchclient.py' }
    if (Test-Path $release) { Remove-Item $release -Recurse -Force }
    Move-Item $staging $release
} finally {
    if (Test-Path $staging) { Remove-Item $staging -Recurse -Force }
}
$script = Join-Path $release 'rchclient.py'
Start-Process -FilePath $py -ArgumentList ('"' + $script + '"') -WorkingDirectory $release -WindowStyle Hidden
Write-Host 'Bootstrap complete.'
'''
